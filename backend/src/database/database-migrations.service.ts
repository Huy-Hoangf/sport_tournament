import { Injectable, OnModuleInit } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import { User } from '../users/user.entity';

@Injectable()
export class DatabaseMigrationsService implements OnModuleInit {
  constructor(
    @InjectRepository(User)
    private readonly usersRepository: Repository<User>,
  ) {}

  async onModuleInit() {
    await this.migrateSportTypes();
    await this.migrateTournamentFormats();
    await this.ensureTournamentDateColumns();
    await this.migrateTournamentStatuses();
    await this.ensureExternalTournamentIdentities();
    await this.ensureScoringRulesTable();
    await this.ensureOutcomeRuleCodes();
    await this.ensureStageNameConstraint();
    await this.ensureActivityLogsTable();
    await this.ensureTeamTimestampColumns();
    await this.ensureTeamPlayersTable();
    await this.ensureLeaderboardView();
    await this.ensureMatchPredictionLock();
  }

  async ensureMatchPredictionLock() {
    await this.usersRepository.query(`
      ALTER TABLE matches ADD COLUMN IF NOT EXISTS prediction_locked BOOLEAN NOT NULL DEFAULT FALSE
    `);
    // API-created manual matches use MANUAL; external sync identities are unaffected.
    await this.usersRepository.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS uq_matches_manual_identity
      ON matches(tournament_id, stage_id, home_team_id, away_team_id, scheduled_time)
      WHERE external_source = 'MANUAL'
    `);
  }

  private async migrateSportTypes() {
    await this.usersRepository.query(`
      ALTER TABLE tournaments
      DROP CONSTRAINT IF EXISTS chk_tournaments_sport_type
    `);
    await this.usersRepository.query(`
      UPDATE tournaments
      SET sport_type = CASE
        WHEN sport_type = 'ESPORTS' THEN 'LOL'
        WHEN sport_type = 'BASKETBALL' THEN 'OTHER'
        ELSE sport_type
      END
      WHERE sport_type IN ('ESPORTS', 'BASKETBALL')
    `);
    await this.usersRepository.query(`
      ALTER TABLE tournaments
      ADD CONSTRAINT chk_tournaments_sport_type
      CHECK (sport_type IN ('FOOTBALL', 'F1', 'LOL', 'OTHER'))
    `);
  }

  private async migrateTournamentFormats() {
    await this.usersRepository.query(`
      ALTER TABLE tournaments
      DROP CONSTRAINT IF EXISTS chk_tournaments_format
    `);
    await this.usersRepository.query(`
      UPDATE tournaments
      SET format = 'ROUND_ROBIN'
      WHERE format IS NULL
         OR format NOT IN ('GROUP_AND_KNOCKOUT', 'ROUND_ROBIN', 'KNOCKOUT', 'CUSTOM')
    `);
    await this.usersRepository.query(`
      ALTER TABLE tournaments
      ADD CONSTRAINT chk_tournaments_format
      CHECK (format IN ('GROUP_AND_KNOCKOUT', 'ROUND_ROBIN', 'KNOCKOUT', 'CUSTOM'))
    `);
    await this.usersRepository.query(`
      CREATE TABLE IF NOT EXISTS tournament_custom_formats (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tournament_id INTEGER NOT NULL UNIQUE REFERENCES tournaments(id) ON DELETE CASCADE,
        name VARCHAR(255) NOT NULL,
        definition JSONB NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);
  }

  private async ensureExternalTournamentIdentities() {
    await this.usersRepository
      .query(`CREATE TABLE IF NOT EXISTS tournament_external_identities (
      provider VARCHAR(50) NOT NULL, competition_id VARCHAR(255) NOT NULL,
      season VARCHAR(100) NOT NULL, tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
      PRIMARY KEY (provider, competition_id, season)
    )`);
  }

  private async ensureScoringRulesTable() {
    await this.usersRepository.query(`
      CREATE TABLE IF NOT EXISTS scoring_rules (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        tournament_id INTEGER NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
        category VARCHAR(100) NOT NULL DEFAULT 'CUSTOM',
        title VARCHAR(255) NOT NULL,
        content TEXT NOT NULL,
        points INTEGER NOT NULL DEFAULT 0,
        sort_order INTEGER NOT NULL DEFAULT 0,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        CONSTRAINT chk_scoring_rules_points CHECK (points >= 0)
      )
    `);
    await this.usersRepository.query(`
      CREATE INDEX IF NOT EXISTS idx_scoring_rules_tournament
      ON scoring_rules(tournament_id, sort_order, id)
    `);
  }

  private async ensureOutcomeRuleCodes() {
    await this.usersRepository.query(
      `ALTER TABLE scoring_rules ADD COLUMN IF NOT EXISTS rule_code VARCHAR(40)`,
    );
    await this.usersRepository.query(`WITH candidates AS (
      SELECT id, row_number() OVER (PARTITION BY tournament_id ORDER BY id) AS n
      FROM scoring_rules WHERE lower(title) = 'correct match winner'
      AND NOT EXISTS (SELECT 1 FROM scoring_rules existing WHERE existing.tournament_id = scoring_rules.tournament_id AND existing.rule_code = 'CORRECT_OUTCOME')
    ) UPDATE scoring_rules SET rule_code = 'CORRECT_OUTCOME' FROM candidates WHERE scoring_rules.id = candidates.id AND candidates.n = 1`);
    await this.usersRepository.query(
      `CREATE UNIQUE INDEX IF NOT EXISTS uq_scoring_rules_outcome ON scoring_rules(tournament_id, rule_code) WHERE rule_code IS NOT NULL`,
    );
  }

  private async ensureStageNameConstraint() {
    await this.usersRepository.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS uq_stages_tournament_name
      ON stages(tournament_id, LOWER(name))
    `);
  }

  private async ensureTournamentDateColumns() {
    await this.usersRepository.query(`
      ALTER TABLE tournaments
      ADD COLUMN IF NOT EXISTS start_date TIMESTAMPTZ NULL
    `);
    await this.usersRepository.query(`
      ALTER TABLE tournaments
      ADD COLUMN IF NOT EXISTS end_date TIMESTAMPTZ NULL
    `);
    await this.usersRepository.query(`
      WITH match_ranges AS (
        SELECT
          tournament_id,
          MIN(scheduled_time) AS start_date,
          MAX(scheduled_time) AS end_date
        FROM matches
        GROUP BY tournament_id
      )
      UPDATE tournaments t
      SET
        start_date = COALESCE(t.start_date, match_ranges.start_date),
        end_date = COALESCE(t.end_date, match_ranges.end_date)
      FROM match_ranges
      WHERE match_ranges.tournament_id = t.id
        AND (t.start_date IS NULL OR t.end_date IS NULL)
    `);
    await this.usersRepository.query(`
      WITH football_api_match_ranges AS (
        SELECT
          m.tournament_id,
          MIN(m.scheduled_time) AS start_date,
          MAX(m.scheduled_time) AS end_date
        FROM matches m
        JOIN tournaments t ON t.id = m.tournament_id
        WHERE t.sport_type = 'FOOTBALL'
          AND m.external_source IN ('FOOTBALL_DATA', 'ESPN_ASEAN')
        GROUP BY m.tournament_id
      )
      UPDATE tournaments t
      SET
        start_date = football_api_match_ranges.start_date,
        end_date = football_api_match_ranges.end_date
      FROM football_api_match_ranges
      WHERE football_api_match_ranges.tournament_id = t.id
    `);
  }

  private async migrateTournamentStatuses() {
    await this.usersRepository.query(`
      ALTER TABLE tournaments
      DROP CONSTRAINT IF EXISTS chk_tournaments_status
    `);
    await this.usersRepository.query(`
      DO $$
      DECLARE
        constraint_name TEXT;
      BEGIN
        FOR constraint_name IN
          SELECT con.conname
          FROM pg_constraint con
          JOIN pg_class rel ON rel.oid = con.conrelid
          JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
          WHERE rel.relname = 'tournaments'
            AND con.contype = 'c'
            AND pg_get_constraintdef(con.oid) ILIKE '%status%'
        LOOP
          EXECUTE format('ALTER TABLE tournaments DROP CONSTRAINT IF EXISTS %I', constraint_name);
        END LOOP;
      END $$;
    `);
    await this.usersRepository.query(`
      UPDATE tournaments
      SET status = CASE
        WHEN status IN ('ACTIVE', 'LIVE', 'ONGOING') THEN 'ONGOING'
        WHEN status IN ('COMPLETED', 'COMPLETE', 'FINISHED', 'CANCELLED', 'CANCELED') THEN 'COMPLETE'
        ELSE 'UPCOMING'
      END
      WHERE status IS NULL
         OR status NOT IN ('UPCOMING', 'ONGOING', 'COMPLETE')
    `);
    await this.usersRepository.query(`
      UPDATE tournaments
      SET status = CASE
        WHEN end_date IS NOT NULL AND end_date < NOW() THEN 'COMPLETE'
        WHEN start_date IS NOT NULL AND start_date > NOW() THEN 'UPCOMING'
        WHEN start_date IS NOT NULL AND start_date <= NOW()
          AND (end_date IS NULL OR end_date >= NOW()) THEN 'ONGOING'
        ELSE status
      END
    `);
    await this.usersRepository.query(`
      ALTER TABLE tournaments
      ADD CONSTRAINT chk_tournaments_status
      CHECK (status IN ('UPCOMING', 'ONGOING', 'COMPLETE'))
    `);
  }

  private async ensureTeamPlayersTable() {
    await this.usersRepository.query(`
      CREATE TABLE IF NOT EXISTS team_players (
        id SERIAL PRIMARY KEY,
        team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
        name VARCHAR(120) NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);
    await this.usersRepository.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS uq_team_players_team_name
      ON team_players(team_id, LOWER(name))
    `);
    await this.usersRepository.query(`
      ALTER TABLE team_players
      ADD COLUMN IF NOT EXISTS user_id INTEGER REFERENCES users(id) ON DELETE SET NULL
    `);
    await this.usersRepository.query(`
      UPDATE team_players tp
      SET user_id = u.id
      FROM users u
      WHERE tp.user_id IS NULL
        AND (
          LOWER(TRIM(tp.name)) = LOWER(TRIM(u.full_name))
          OR LOWER(TRIM(tp.name)) = LOWER(TRIM(u.email))
          OR LOWER(TRIM(tp.name)) = LOWER(TRIM(COALESCE(u.member_code, '')))
        )
    `);
    await this.usersRepository.query(`
      CREATE UNIQUE INDEX IF NOT EXISTS uq_team_players_team_user
      ON team_players(team_id, user_id)
      WHERE user_id IS NOT NULL
    `);
  }

  private async ensureActivityLogsTable() {
    await this.usersRepository.query(`
      CREATE TABLE IF NOT EXISTS activity_logs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        type VARCHAR(50) NOT NULL,
        message TEXT NOT NULL,
        tournament_id INTEGER NULL,
        tournament_visibility VARCHAR(20) NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);
    await this.usersRepository.query(`
      CREATE INDEX IF NOT EXISTS idx_activity_logs_created_at
      ON activity_logs(created_at DESC)
    `);
  }

  private async ensureLeaderboardView() {
    await this.usersRepository.query(`
      CREATE OR REPLACE VIEW vw_leaderboard AS
      WITH scored AS (
        SELECT
          t.id AS tournament_id,
          u.id AS user_id,
          u.full_name,
          u.email,
          p.id AS prediction_id,
          p.predicted_outcome,
          p.predicted_home_score,
          p.predicted_away_score,
          m.actual_home_score,
          m.actual_away_score,
          COALESCE((SELECT sr.points FROM scoring_rules sr WHERE sr.tournament_id = t.id AND sr.rule_code = 'CORRECT_OUTCOME' LIMIT 1), 3) AS correct_points,
          CASE
            WHEN m.status = 'FINISHED'
              AND m.actual_home_score IS NOT NULL
              AND m.actual_away_score IS NOT NULL
            THEN CASE
              WHEN m.actual_home_score > m.actual_away_score THEN 'HOME_WIN'
              WHEN m.actual_home_score < m.actual_away_score THEN 'AWAY_WIN'
              ELSE 'DRAW'
            END
            ELSE NULL
          END AS actual_outcome
        FROM predictions p
        JOIN users u ON u.id = p.user_id
        JOIN matches m ON m.id = p.match_id
        JOIN tournaments t ON t.id = m.tournament_id
        JOIN stages s ON s.id = m.stage_id
      )
      SELECT
        tournament_id,
        user_id,
        full_name,
        email,
        SUM(
          CASE WHEN predicted_outcome = actual_outcome
            THEN correct_points ELSE 0 END

        ) AS total_points,
        COUNT(prediction_id) AS total_predictions,
        SUM(CASE WHEN predicted_outcome = actual_outcome THEN 1 ELSE 0 END)
          AS correct_predictions
      FROM scored
      GROUP BY tournament_id, user_id, full_name, email
    `);
  }

  private async ensureTeamTimestampColumns() {
    await this.usersRepository.query(`
      ALTER TABLE teams
      ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    `);
    await this.usersRepository.query(`
      ALTER TABLE teams
      ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    `);
  }
}
